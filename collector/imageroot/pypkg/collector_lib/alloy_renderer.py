def _render_relabel_block(
    block_name: str,
    *,
    customer: str,
    site: str,
    device_role: str,
    collector_id: str,
) -> list[str]:
    return [
        f'prometheus.relabel "{block_name}" {{',
        "  rule {",
        '    target_label = "customer"',
        f"    replacement  = {_river_str(customer)}",
        "  }",
        "",
        "  rule {",
        '    target_label = "site"',
        f"    replacement  = {_river_str(site)}",
        "  }",
        "",
        "  rule {",
        '    target_label = "device_role"',
        f"    replacement  = {_river_str(device_role)}",
        "  }",
        "",
        "  rule {",
        '    target_label = "collector_id"',
        f"    replacement  = {_river_str(collector_id)}",
        "  }",
        "",
        "  forward_to = [prometheus.remote_write.hub.receiver]",
        "}",
    ]


def _wal_tuning(wal_max_disk_mb: int) -> tuple[int, str, str]:
    if wal_max_disk_mb < 512:
        return 5000, "1h", "2h"
    if wal_max_disk_mb >= 8192:
        return 25000, "2h", "24h"
    return 10000, "2h", "8h"


