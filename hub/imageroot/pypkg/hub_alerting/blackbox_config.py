def render_blackbox_config(output_path: Path | None = None, *, state_dir: str | Path | None = None) -> str:
    """Write blackbox.yml atomically with LF line endings and return rendered YAML."""
    target_path = output_path or (resolve_config_dir(state_dir) / "blackbox" / "blackbox.yml")
    atomic_write_text(target_path, BLACKBOX_YAML_TEMPLATE, mode=0o644)
    return BLACKBOX_YAML_TEMPLATE
